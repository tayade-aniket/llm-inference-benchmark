"""
Abstract Base Engine Interface for Inference Benchmarking.
"""

from abc import ABC, abstractmethod
from typing import Dict, List, Optional, Tuple


class BaseInferenceEngine(ABC):
    def __init__(self, model_id_or_path: str, config: Optional[Dict] = None):
        self.model_id_or_path = model_id_or_path
        self.config = config or {}
        self.is_loaded = False
        self.memory_before_load_mb: Optional[float] = None
        self.memory_after_load_mb: Optional[float] = None

    @abstractmethod
    def load_model(self) -> None:
        """Loads model weights and tokenizer into memory."""
        pass

    @abstractmethod
    def generate(
        self,
        prompt: str,
        max_new_tokens: int = 32,
        temperature: float = 0.0,
    ) -> Tuple[str, List[float], int, int]:
        """
        Executes autoregressive generation with token streaming.

        Returns:
            Tuple of:
            - output_text: Decoded string generated by the model.
            - token_timestamps_s: List of monotonic timestamps when each token arrived.
            - prompt_tokens: Number of prompt tokens evaluated during prefill.
            - generated_tokens: Number of output tokens generated.
        """
        pass

    @abstractmethod
    def unload_model(self) -> None:
        """Unloads weights from memory and runs garbage collection."""
        pass

    @abstractmethod
    def get_model_size_mb(self) -> float:
        """Returns the size of the model file/weights on disk in MB."""
        pass
